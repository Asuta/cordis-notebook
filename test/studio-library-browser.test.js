test('素材库浏览器：目录与收藏集、多窗口多标签、缩放拖动、批量画布引用和回收恢复', { skip: process.env.CORDIS_BROWSER_TEST !== '1', timeout: 65000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'cordis-library-browser-'))
  let host, browser, page
  t.after(async () => {
    if (page && process.env.CORDIS_BROWSER_ARTIFACT_DIR) {
      const output = resolve(process.env.CORDIS_BROWSER_ARTIFACT_DIR); await mkdir(output, { recursive: true })
      await page.screenshot({ path: join(output, 'studio-library.png'), fullPage: true }).catch(() => {})
    }
    await browser?.close(); await host?.close(); await rm(dir, { recursive: true, force: true })
  })
  host = await createHost({ port: 0, dataDir: dir, locationRoot: dir, initialApplication: 'studio' })
  const origin = 'http://127.0.0.1:' + host.server.address().port
  const request = async (path = '', body) => {
    const response = await fetch(origin + '/api/studio' + path, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', 'X-Application-Session': host.applications.session }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
    assert.equal(response.status, 200, await response.clone().text()); return response.json()
  }
  for (let i = 0; i < 12; i++) {
    const image = await sharp({ create: { width: 160 + i * 4, height: 120, channels: 3, background: ['#91ad76', '#e1b897', '#8faeb8'][i % 3] } }).png().toBuffer()
    await request('/upload', { name: '素材 ' + String(i).padStart(2, '0'), base64: image.toString('base64') })
  }
  browser = await chromium.launch({ headless: true })
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(10000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(origin)
  await page.locator('.studio-sidebar-tab[data-side-page=assets]').click()
  const side = page.locator('.asset-sidebar'), windows = page.locator('.asset-window')
  await until(async () => await side.locator('.asset-tile').count() > 0)
  await until(() => side.locator('.asset-tile img').first().evaluate(image => image.complete && image.naturalWidth > 0))
  await page.locator('.studio-asset-expand').click()
  const first = windows.nth(0)
  await first.getByRole('button', { name: '＋ 窗口', exact: true }).click()
  assert.equal(await windows.count(), 2)
  const second = windows.nth(1)
  await second.getByLabel('新建素材库标签页', { exact: true }).click()
  assert.equal(await second.getByRole('tab').count(), 2)
  await second.getByLabel('搜索素材', { exact: true }).fill('素材 00')
  await until(async () => await second.locator('.asset-tile').count() === 1)
  await second.getByRole('tab').first().click()
  assert.equal(await second.getByLabel('搜索素材', { exact: true }).inputValue(), '')
  await second.getByRole('tab').nth(1).click()
  assert.equal(await second.getByLabel('搜索素材', { exact: true }).inputValue(), '素材 00')
  await second.getByLabel('搜索素材', { exact: true }).fill('')
  const sizeBefore = Number(await second.getByLabel('缩略图大小', { exact: true }).inputValue())
  await second.locator('.asset-grid').hover(); await page.keyboard.down('Control'); await page.mouse.wheel(0, -120); await page.keyboard.up('Control')
  await until(async () => Number(await second.getByLabel('缩略图大小', { exact: true }).inputValue()) > sizeBefore)
  assert.equal(Number(await first.getByLabel('缩略图大小', { exact: true }).inputValue()), sizeBefore)
  const beforeMove = await second.boundingBox(), head = await second.locator('.asset-window-head strong').boundingBox()
  await page.mouse.move(head.x + 30, head.y + 8); await page.mouse.down(); await page.mouse.move(head.x + 85, head.y + 38, { steps: 5 }); await page.mouse.up()
  const moved = await second.boundingBox(); assert.ok(moved.x > beforeMove.x + 30)
  const handle = await second.locator('.resize-se').boundingBox()
  await page.mouse.move(handle.x + 5, handle.y + 5); await page.mouse.down(); await page.mouse.move(handle.x + 65, handle.y + 45, { steps: 5 }); await page.mouse.up()
  assert.ok((await second.boundingBox()).width > moved.width + 30)
  await second.getByRole('button', { name: '关闭', exact: true }).click()
  const confirm = async value => {
    const dialog = page.locator('.asset-library-dialog')
    await dialog.waitFor({ state: 'visible' })
    if (value !== undefined) { if (await dialog.locator('select').count()) await dialog.locator('select').selectOption(value); else await dialog.locator('input').fill(value) }
    await dialog.getByRole('button', { name: '确定', exact: true }).click()
    await dialog.waitFor({ state: 'detached' })
  }
  await first.getByRole('button', { name: '新建文件夹', exact: true }).click(); await confirm('人物')
  let library
  await until(async () => { library = await request('/asset-library'); return library.folders.length === 1 })
  const folderId = library.folders[0].id
  const tiles = first.locator('.asset-tile')
  await tiles.nth(0).click(); await tiles.nth(1).click({ modifiers: ['Control'] })
  assert.equal(await first.locator('.asset-tile.selected').count(), 2)
  await first.getByRole('button', { name: '移动到…', exact: true }).click(); await confirm(folderId)
  await first.locator('[data-location="folder:' + folderId + '"]').click()
  await until(async () => await tiles.count() === 2)
  await first.getByRole('button', { name: '新建收藏集', exact: true }).click(); await confirm('造型参考')
  await until(async () => { library = await request('/asset-library'); return library.collections.length === 2 })
  const collectionId = library.collections[1].id
  await first.locator('.asset-grid').focus(); await page.keyboard.press('Control+a')
  await first.getByRole('button', { name: '加入收藏集', exact: true }).click(); await confirm(collectionId)
  await until(async () => (await request('/asset-library')).collections[1].assetIds.length === 2)
  await page.locator('.studio-sidebar-collapse').click()
  assert.equal(await page.locator('.studio-sidebar').isVisible(), false)
  assert.equal(await first.isVisible(), true)
  const nodeCount = (await request()).boards[0].nodes.length
  await tiles.first().dragTo(page.locator('.studio-stage'), { targetPosition: { x: 1270, y: 760 } })
  await until(async () => (await request()).boards[0].nodes.length === nodeCount + 2, '多选拖入没有创建两张卡片')
  await first.getByRole('button', { name: '更多 ⋯', exact: true }).click()
  await first.getByRole('menu').getByRole('button', { name: '移入回收站', exact: true }).click(); await confirm()
  await first.locator('[data-location=trash]').click()
  await until(async () => await tiles.count() === 2)
  await first.locator('.asset-grid').focus(); await page.keyboard.press('Control+a')
  await first.getByRole('button', { name: '更多 ⋯', exact: true }).click()
  await first.getByRole('menu').getByRole('button', { name: '恢复所选', exact: true }).click()
  await until(async () => await tiles.count() === 0)
  await first.locator('[data-location="collection:' + collectionId + '"]').click()
  await until(async () => await tiles.count() === 2)
  await first.getByLabel('新建素材库标签页', { exact: true }).click()
  await until(() => page.evaluate(() => Object.entries(localStorage).some(([key, value]) => key.includes('studio-asset-workspace-v1') && JSON.parse(value).windows[0]?.tabs.length === 2)))
  await page.reload()
  await page.locator('.asset-window').waitFor()
  assert.equal(await page.locator('.studio-sidebar').isVisible(), false)
  assert.equal(await windows.nth(0).getByRole('tab').count(), 2)
  await page.locator('.studio-sidebar-toggle').click()
  assert.equal(await page.locator('.studio-sidebar').isVisible(), true)
  // A deletion in another page must disappear from an already-loaded session.
  const state = await request(), latestLibrary = await request('/asset-library')
  const unused = Object.values(state.assets).find(asset => !latestLibrary.items[asset.id]?.folderId)
  await windows.nth(0).locator('[data-location=all]').click()
  await windows.nth(0).getByLabel('搜索素材', { exact: true }).fill(unused.name)
  await until(async () => await windows.nth(0).locator('.asset-tile').count() === 1)
  const trashed = await request('/asset-library', { revision: latestLibrary.revision, type: 'trash', ids: [unused.id] })
  await request('/asset-library/purge', { revision: trashed.revision, ids: [unused.id] })
  await until(async () => await windows.nth(0).locator('.asset-tile').count() === 0, '其他页面永久删除后仍出现旧素材')
  await windows.nth(0).getByLabel('搜索素材', { exact: true }).fill('')
  await page.locator('.studio-theme-toggle').click()
  assert.deepEqual(errors, [])
})

test('素材库浏览器：滚动复用图片和视频封面，简略模式独立持久化且保留交互', { skip: process.env.CORDIS_BROWSER_TEST !== '1', timeout: 65000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'cordis-library-scroll-'))
  let host, browser, page
  t.after(async () => {
    if (page && process.env.CORDIS_BROWSER_ARTIFACT_DIR) {
      const output = resolve(process.env.CORDIS_BROWSER_ARTIFACT_DIR); await mkdir(output, { recursive: true })
      await page.screenshot({ path: join(output, 'studio-library-compact.png'), animations: 'disabled' }).catch(() => {})
    }
    await browser?.close(); await host?.close(); await rm(dir, { recursive: true, force: true })
  })
  host = await createHost({ port: 0, dataDir: dir, locationRoot: dir, initialApplication: 'studio' })
  const origin = 'http://127.0.0.1:' + host.server.address().port
  const request = async (path = '', body) => {
    const response = await fetch(origin + '/api/studio' + path, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', 'X-Application-Session': host.applications.session }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
    assert.equal(response.status, 200, await response.clone().text()); return response.json()
  }
  const png = await sharp({ create: { width: 128, height: 96, channels: 3, background: '#91ad76' } }).png().toBuffer()
  for (let i = 0; i < 120; i++) await request('/upload', { name: '参考 ' + String(i).padStart(3, '0'), base64: png.toString('base64') })
  const video = await videoFixture('mp4'), upload = await request('/media/uploads', { name: '视频封面.mp4', size: video.length })
  await request('/media/uploads/' + upload.id, { offset: 0, base64: video.toString('base64') })
  const clip = await request('/media/uploads/' + upload.id + '/finish', {})
  browser = await chromium.launch({ headless: true })
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(10000)
  const errors = [], mediaRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', req => { if (req.url().includes('/api/studio/videos/')) mediaRequests.push(req.url()) })
  await page.goto(origin)
  await page.locator('.studio-sidebar-tab[data-side-page=assets]').click()
  await page.locator('.studio-asset-expand').click()
  const first = page.locator('.asset-window').first(), grid = first.locator('.asset-grid')
  const poster = first.locator('[data-key="a:' + clip.id + '"] img')
  await until(() => poster.evaluate(img => img.complete && img.naturalWidth > 0 && img.src.startsWith('data:image/')), '视频封面未生成')
  assert.equal(await first.locator('video').count(), 0)
  const requestCount = mediaRequests.length
  await grid.evaluate(element => {
    window.originalTiles = new Map([...element.querySelectorAll('.asset-tile')].map(tile => [tile.dataset.key, { tile, image: tile.querySelector('img') }]))
    window.removedTiles = new Set()
    window.scrollObserver = new MutationObserver(records => { for (const record of records) for (const node of record.removedNodes) if (node.dataset?.key) window.removedTiles.add(node.dataset.key) })
    window.scrollObserver.observe(element, { subtree: true, childList: true })
    element.scrollTop = 230
  })
  await until(() => grid.evaluate(element => [...element.querySelectorAll('.asset-tile')].some(tile => !window.originalTiles.has(tile.dataset.key))))
  const continuity = await grid.evaluate(element => {
    const common = [...element.querySelectorAll('.asset-tile')].filter(tile => window.originalTiles.has(tile.dataset.key))
    return { count: common.length, stable: common.every(tile => tile === window.originalTiles.get(tile.dataset.key).tile && tile.querySelector('img') === window.originalTiles.get(tile.dataset.key).image && !window.removedTiles.has(tile.dataset.key)) }
  })
  assert.ok(continuity.count > 5); assert.equal(continuity.stable, true, '滚动不得移除或重建仍在可见区的图片')
  await grid.evaluate(element => { element.scrollTop = 3000 })
  await until(() => poster.count().then(count => count === 0))
  await grid.evaluate(element => { element.scrollTop = 0 })
  await until(() => poster.count().then(count => count === 1))
  assert.equal(await poster.evaluate(img => img === window.originalTiles.get(img.closest('[data-key]').dataset.key).image), true, '回滚复用缓存节点')
  await first.getByRole('button', { name: '＋ 窗口', exact: true }).click()
  const second = page.locator('.asset-window').nth(1)
  await until(() => second.locator('[data-kind=video] img').evaluate(img => img.complete && img.naturalWidth > 0))
  assert.equal(mediaRequests.length, requestCount, '第二个窗口应复用视频封面缓存')
  const fullSize = await second.boundingBox()
  await second.getByRole('button', { name: '简略模式', exact: true }).click()
  assert.equal(await first.evaluate(el => el.classList.contains('asset-compact')), false)
  for (const selector of ['.asset-window-head', '.asset-navigation', '.asset-controls', '.asset-actions', '.asset-tree', '.asset-browser-foot']) assert.equal(await second.locator(selector).isVisible(), false)
  const secondGrid = second.locator('.asset-grid'), compactTile = second.locator('.asset-tile').first()
  const box = await second.boundingBox(), gridBox = await secondGrid.boundingBox()
  assert.ok(gridBox.width > box.width - 10 && gridBox.height > box.height - 45, '简略模式仅保留一条紧凑页签栏')
  await second.getByLabel('素材库窗口菜单').hover()
  assert.equal(await compactTile.locator('strong').evaluate(el => getComputedStyle(el).opacity), '0')
  await compactTile.hover()
  assert.equal(await compactTile.locator('strong').evaluate(el => getComputedStyle(el).opacity), '1')
  assert.match(await compactTile.getAttribute('title'), / × /)
  await compactTile.click(); await second.locator('.asset-tile').nth(1).click({ modifiers: ['Control'] })
  assert.equal(await second.locator('.selected').count(), 2)
  const size = Number(await second.getByLabel('缩略图大小').inputValue())
  await secondGrid.hover(); await page.keyboard.down('Control'); await page.mouse.wheel(0, -120); await page.keyboard.up('Control')
  await until(async () => Number(await second.getByLabel('缩略图大小').inputValue()) > size)
  assert.equal(await second.locator('.selected').count(), 2)
  const switchTab = second.getByLabel('切换素材库标签页', { exact: true })
  const tabMenu = second.getByRole('menu', { name: '素材库标签页列表' })
  await switchTab.click()
  await tabMenu.getByLabel('新建素材库标签页', { exact: true }).click()
  assert.equal(await second.getByRole('tab').count(), 0, '简略模式隐藏横向页签')
  assert.equal(await second.locator('.selected').count(), 0)
  await switchTab.click()
  assert.equal(await tabMenu.getByRole('menuitemradio').count(), 2)
  await tabMenu.getByRole('menuitemradio').first().click()
  assert.equal(await second.locator('.selected').count(), 2, '同目录标签页的选择互相独立')
  await switchTab.click()
  await tabMenu.getByLabel('新建素材库标签页', { exact: true }).click()
  await switchTab.click()
  assert.equal(await tabMenu.getByRole('menuitemradio').count(), 3)
  await tabMenu.getByLabel('关闭标签页：全部素材 · 3', { exact: true }).click()
  await switchTab.click()
  assert.equal(await tabMenu.getByRole('menuitemradio').count(), 2)
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  assert.equal(await second.locator('.selected').count(), 2)
  await switchTab.click()
  await page.keyboard.press('Escape')
  assert.equal(await tabMenu.count(), 0)
  const tabBar = await second.locator('.asset-window-grip').boundingBox(), before = await second.boundingBox()
  await page.mouse.move(tabBar.x + 16, tabBar.y + 18); await page.mouse.down(); await page.mouse.move(tabBar.x + 46, tabBar.y + 48, { steps: 4 }); await page.mouse.up()
  assert.ok((await second.boundingBox()).x > before.x + 20, '多个标签页时固定把手仍可拖动')
  const resize = await second.locator('.resize-se').boundingBox(), beforeResize = await second.boundingBox()
  await page.mouse.move(resize.x + 5, resize.y + 5); await page.mouse.down()
  await page.mouse.move(resize.x + 5 - beforeResize.width + 200, resize.y + 5 - beforeResize.height + 160, { steps: 6 }); await page.mouse.up()
  const small = await second.boundingBox()
  assert.equal(small.width, 220); assert.equal(small.height, 180)
  for (const control of [switchTab, second.getByLabel('素材库窗口菜单'), second.getByLabel('关闭素材库窗口'), second.locator('.asset-window-grip')]) {
    const rect = await control.boundingBox()
    assert.ok(rect.width >= 28 && rect.x >= small.x && rect.x + rect.width <= small.x + small.width, '最小尺寸下各顶部控件仍可操作')
  }
  await switchTab.click()
  await tabMenu.getByRole('menuitemradio').first().click()
  await secondGrid.evaluate(el => { el.scrollTop = 700 })
  await until(() => secondGrid.evaluate(el => el.scrollTop >= 700))
  await second.getByLabel('素材库窗口菜单').click()
  await second.getByRole('button', { name: '恢复完整模式', exact: true }).click()
  assert.equal((await second.boundingBox()).width, fullSize.width)
  assert.equal((await second.boundingBox()).height, fullSize.height)
  assert.ok(await secondGrid.evaluate(el => el.scrollTop > 0), '恢复完整模式不跳回目录顶部')
  await second.getByRole('button', { name: '简略模式', exact: true }).click()
  assert.equal((await second.boundingBox()).width, small.width)
  assert.equal((await second.boundingBox()).height, small.height)
  await until(() => page.evaluate(() => Object.entries(localStorage).some(([key, value]) => { if (!key.includes('studio-asset-workspace-v1')) return false; const window = JSON.parse(value).windows[1]; return window?.compact === true && window.tabs[window.activeIndex].scroll > 0 })))
  await page.reload()
  await page.locator('.asset-window.asset-compact').waitFor()
  const restored = page.locator('.asset-window.asset-compact')
  assert.equal((await restored.boundingBox()).width, small.width)
  assert.equal((await restored.boundingBox()).height, small.height)
  await restored.getByLabel('切换素材库标签页', { exact: true }).click()
  assert.equal(await restored.getByRole('menuitemradio').count(), 2)
  await page.keyboard.press('Escape')
  await until(() => page.locator('.asset-window.asset-compact .asset-grid').evaluate(el => el.scrollTop > 0), '重载后恢复简略模式滚动位置')
  assert.equal(await page.locator('.asset-window:not(.asset-compact)').count(), 1)
  assert.deepEqual(errors, [])
})
