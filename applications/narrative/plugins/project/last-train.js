const stage = (background, characterId = 'lin', expression = 'neutral') => ({
  background, characterId, expression, position: 62, scale: 100,
})
const choice = (id, text, target, trust = 0, condition) => ({
  id, text, target,
  actions: trust ? [{ type: 'add-variable', variable: 'trust', value: trust }] : [],
  ...(condition ? { condition: { type: 'variable', variable: 'trust', ...condition } } : {}),
})
const story = (id, title, scene, lines, next, choices = []) => ({
  id, type: 'story', title, stage: scene, lines, choices, ...(next ? { next } : {}),
})
const ending = (id, title, scene, lines) => ({ id, type: 'ending', title, stage: scene, lines, choices: [] })

